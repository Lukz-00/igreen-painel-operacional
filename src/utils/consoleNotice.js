export function startConsoleNotice() {
  if (typeof window === 'undefined') return
  if (window.__IGREEN_CONSOLE_NOTICE__) return

  window.__IGREEN_CONSOLE_NOTICE__ = {
    startedAt: Date.now(),
    intervalMs: NOTICE_INTERVAL_MS,
    timer: window.setInterval(printNotice, NOTICE_INTERVAL_MS),
  }

  printNotice()
}
